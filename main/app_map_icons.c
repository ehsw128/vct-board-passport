int app_map_icons_find(const char *en) {
    if (en == NULL || en[0] == '\0') return -1;
    for (unsigned i = 0; i < sizeof(APP_MAP_ICONS) / sizeof(APP_MAP_ICONS[0]); i++) {
        if (strcmp(APP_MAP_ICONS[i].en, en) == 0) return (int)i;
    }
    return -1;
}

int app_map_icons_count(void) {
    return (int)(sizeof(APP_MAP_ICONS) / sizeof(APP_MAP_ICONS[0]));
}

const void *app_map_icons_dsc(int idx) {
    return (idx >= 0 && idx < app_map_icons_count()) ? APP_MAP_ICONS[idx].dsc : NULL;
}
